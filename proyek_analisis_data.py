rfm_df["M_score"] = pd.qcut(rfm_df["monetary"].rank(method="first"), 5, labels=[1, 2, 3, 4, 5]).astype(int)
# Manual grouping (clustering berbasis aturan bisnis, tanpa machine learning)
def segment(row):
    if row["frequency"] >= 2:
        return "Champions" if row["R_score"] >= 4 else "Loyal Customers"
    if row["R_score"] >= 4:
        return "Big Spender Baru" if row["M_score"] >= 4 else "Pelanggan Baru"
    if row["R_score"] == 3:
        return "Need Attention"
    return "At Risk (Big Spender)" if row["M_score"] >= 4 else "Hibernating"
rfm_df["segment"] = rfm_df.apply(segment, axis=1)
seg_summary = (rfm_df.groupby("segment").agg(
                    customers=("customer_unique_id", "count"),
                    avg_recency=("recency", "mean"),
                    avg_frequency=("frequency", "mean"),
                    avg_monetary=("monetary", "mean"),
                    total_monetary=("monetary", "sum"))
               .sort_values("customers", ascending=False))
seg_summary["customer_share_%"] = seg_summary["customers"] / seg_summary["customers"].sum() * 100
seg_summary["revenue_share_%"] = seg_summary["total_monetary"] / seg_summary["total_monetary"].sum() * 100
